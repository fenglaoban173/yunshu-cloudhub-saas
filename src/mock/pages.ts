/**
 * 从实际数据里取出某一列的全部取值，作为下拉筛选项。
 * 直接由数据推导，筛选项和数据永远对得上 —— 不会出现「下拉是空的，点开没得选」。
 */
const optsOf = (rows: Record<string, any>[], key: string) =>
  [...new Set(rows.map((r) => String(r?.[key] ?? '')).filter(Boolean))]
    .sort((a, b) => a.localeCompare(b, 'zh-CN'))
    .map((v) => ({ label: v, value: v }))

